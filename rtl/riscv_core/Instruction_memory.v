module Instruction_memory(
    input   wire    [31:0]  pc,

    output  wire    [31:0]  Instruction
);

    reg [31:0]  mem [0:1023];

    initial begin

        // =========================================================
        // AES CONTROL = ENCRYPT
        // 0x08 = 0x02
        // =========================================================

        mem[0] = 32'h00800293;     // addi x5,x0,8
        mem[1] = 32'h00200313;     // addi x6,x0,2
        mem[2] = 32'h0062A023;     // sw x6,0(x5)


        // =========================================================
        // ECC MODE = ENROLLMENT
        // 0x0C = 0x00
        // =========================================================

        mem[3] = 32'h00C00293;     // addi x5,x0,0x0C
        mem[4] = 32'h00000313;     // addi x6,x0,0
        mem[5] = 32'h0062A023;     // sw x6,0(x5)


        // =========================================================
        // PUF CHALLENGE
        //
        // Challenge = 0x12345678
        // =========================================================

        mem[6] = 32'h01400293;     // addi x5,x0,0x14

        // x6 = 0x12345678
        mem[7] = 32'h12345337;     // lui  x6,0x12345
        mem[8] = 32'h67830313;     // addi x6,x6,0x678

        // PUF_CHALLENGE[31:0] = 0x12345678
        mem[9] = 32'h0062A023;     // sw x6,0(x5)


        // =========================================================
        // PUF WINDOW
        // 0x18 = 50
        // =========================================================

        mem[10] = 32'h01800293;     // addi x5,x0,0x18
        mem[11] = 32'h03200313;     // addi x6,x0,50
        mem[12] = 32'h0062A023;     // sw x6,0(x5)


        // =========================================================
        // PLAINTEXT
        //
        // 128-bit plaintext:
        //
        // 11111111_22222222_33333333_44444444
        //
        // 0x20 = 11111111
        // 0x24 = 22222222
        // 0x28 = 33333333
        // 0x2C = 44444444
        // =========================================================


        // ---------------------------------------------------------
        // PT[31:0] = 0x11111111
        // ---------------------------------------------------------

        mem[13] = 32'h02000293;     // addi x5,x0,0x20

        mem[14] = 32'h11111337;     // lui  x6,0x11111
        mem[15] = 32'h11130313;     // addi x6,x6,0x111

        mem[16] = 32'h0062A023;     // sw x6,0(x5)


        // ---------------------------------------------------------
        // PT[63:32] = 0x22222222
        // ---------------------------------------------------------

        mem[17] = 32'h02400293;     // addi x5,x0,0x24

        mem[18] = 32'h22222337;     // lui  x6,0x22222
        mem[19] = 32'h22230313;     // addi x6,x6,0x222

        mem[20] = 32'h0062A023;     // sw x6,0(x5)


        // ---------------------------------------------------------
        // PT[95:64] = 0x33333333
        // ---------------------------------------------------------

        mem[21] = 32'h02800293;     // addi x5,x0,0x28

        mem[22] = 32'h33333337;     // lui  x6,0x33333
        mem[23] = 32'h33330313;     // addi x6,x6,0x333

        mem[24] = 32'h0062A023;     // sw x6,0(x5)


        // ---------------------------------------------------------
        // PT[127:96] = 0x44444444
        // ---------------------------------------------------------

        mem[25] = 32'h02C00293;     // addi x5,x0,0x2C

        mem[26] = 32'h44444337;     // lui  x6,0x44444
        mem[27] = 32'h44430313;     // addi x6,x6,0x444

        mem[28] = 32'h0062A023;     // sw x6,0(x5)


        // =========================================================
        // START
        // 0x00 = 1
        // =========================================================

        mem[29] = 32'h00000293;     // addi x5,x0,0
        mem[30] = 32'h00100313;     // addi x6,x0,1
        mem[31] = 32'h0062A023;     // sw x6,0(x5)


        // =========================================================
        // STATUS ADDRESS
        // x5 = 0x04
        // =========================================================

        mem[32] = 32'h00400293;     // addi x5,x0,0x04


        // =========================================================
        // POLL STATUS
        //
        // STATUS:
        // bit[0] = BUSY
        // bit[1] = DONE
        // bit[2] = ERROR
        // =========================================================

        // lw x7,0(x5)
        mem[33] = 32'h0002A383;

        // andi x8,x7,4
        // ERROR bit
        mem[34] = 32'h0043F413;

        // if ERROR != 0 -> error_loop
        mem[35] = 32'h02041863;

        // andi x8,x7,2
        // DONE bit
        mem[36] = 32'h0023F413;

        // if DONE == 0 -> poll_status
        mem[37] = 32'hFE0408E3;


        // =========================================================
        // READ AES OUTPUT
        // =========================================================

        // AES_OUT_0 = 0x40
        mem[38] = 32'h04000293;
        mem[39] = 32'h0002A503;

        // AES_OUT_1 = 0x44
        mem[40] = 32'h04400293;
        mem[41] = 32'h0002A583;

        // AES_OUT_2 = 0x48
        mem[42] = 32'h04800293;
        mem[43] = 32'h0002A603;

        // AES_OUT_3 = 0x4C
        mem[44] = 32'h04C00293;
        mem[45] = 32'h0002A683;


        // =========================================================
        // SUCCESS LOOP
        // =========================================================

        mem[46] = 32'h0000006F;


        // =========================================================
        // ERROR LOOP
        // =========================================================

        mem[47] = 32'h0000006F;

    end

    assign Instruction = mem[pc[31:2]];

endmodule