module Instruction_memory(
input  wire [31:0] pc,
output wire [31:0] Instruction
);

reg [31:0] mem [0:1023];

initial begin

    // =========================================================
    // INITIAL CONFIGURATION WRITES
    // =========================================================

    // UART is mapped at 0x1000-0x13FF; HADDR forwards its low 10 bits.
    // Write: UART address 0x1100 – data 0x00000000
    mem[0] = 32'h000012B7;     // lui  x5,0x1
    mem[1] = 32'h10028293;     // addi x5,x5,0x100
    mem[2] = 32'h00000313;     // addi x6,x0,0
    mem[3] = 32'h0062A023;     // sw x6,0(x5)

    // Write: UART address 0x1104 – data 0x0000001B
    // (25 MHz / 16 / 57600, matching the SoC clock)
    mem[4] = 32'h00428293;     // addi x5,x5,0x004
    mem[5] = 32'h01B00313;     // addi x6,x0,0x1B
    mem[6] = 32'h0062A023;     // sw x6,0(x5)

    // Write: UART address 0x1108 – data 0x00000000
    mem[7] = 32'h00428293;     // addi x5,x5,0x004
    mem[8] = 32'h00000313;     // addi x6,x0,0
    mem[9] = 32'h0062A023;     // sw x6,0(x5)


    // =========================================================
    // Write: address 0x10C – data 0x00000023
    // CHÈN NOP TẠI ĐÂY
    // =========================================================

    mem[10] = 32'h00428293;    // addi x5,x5,0x004
    mem[11] = 32'h02300313;    // addi x6,x0,0x23

    mem[12] = 32'h00000013;    // NOP
    mem[13] = 32'h00000013;    // NOP

    mem[14] = 32'h0062A023;    // sw x6,0(x5)


    // =========================================================
    // AES CONTROL = ENCRYPT
    // 0x08 = 0x02
    // =========================================================

    mem[15] = 32'h00800293;    // addi x5,x0,8
    mem[16] = 32'h00200313;    // addi x6,x0,2
    mem[17] = 32'h0062A023;    // sw x6,0(x5)


    // =========================================================
    // ECC MODE = ENROLLMENT
    // 0x0C = 0x00
    // =========================================================

    mem[18] = 32'h00C00293;    // addi x5,x0,0x0C
    mem[19] = 32'h00000313;    // addi x6,x0,0
    mem[20] = 32'h0062A023;    // sw x6,0(x5)


    // =========================================================
    // PUF CHALLENGE
    // Challenge = 0x12345678
    // =========================================================

    mem[21] = 32'h01400293;    // addi x5,x0,0x14

    mem[22] = 32'h12345337;    // lui  x6,0x12345
    mem[23] = 32'h67830313;    // addi x6,x6,0x678

    mem[24] = 32'h0062A023;    // sw x6,0(x5)


    // =========================================================
    // PUF WINDOW
    // 0x18 = 50
    // =========================================================

    mem[25] = 32'h01800293;    // addi x5,x0,0x18
    mem[26] = 32'h03200313;    // addi x6,x0,50
    mem[27] = 32'h0062A023;    // sw x6,0(x5)


    // =========================================================
    // PLAINTEXT
    //
    // 128-bit plaintext:
    // 11111111_22222222_33333333_44444444
    // =========================================================


    // ---------------------------------------------------------
    // PT[31:0] = 0x11111111
    // ---------------------------------------------------------

    mem[30] = 32'h02000293;    // addi x5,x0,0x20

    mem[31] = 32'h11111337;    // lui x6,0x11111
    mem[32] = 32'h11130313;    // addi x6,x6,0x111

    mem[33] = 32'h0062A023;    // sw x6,0(x5)


    // ---------------------------------------------------------
    // PT[63:32] = 0x22222222
    // ---------------------------------------------------------

    mem[34] = 32'h02400293;    // addi x5,x0,0x24

    mem[35] = 32'h22222337;    // lui x6,0x22222
    mem[36] = 32'h22230313;    // addi x6,x6,0x222

    mem[37] = 32'h0062A023;    // sw x6,0(x5)


    // ---------------------------------------------------------
    // PT[95:64] = 0x33333333
    // ---------------------------------------------------------

    mem[38] = 32'h02800293;    // addi x5,x0,0x28

    mem[39] = 32'h33333337;    // lui x6,0x33333
    mem[40] = 32'h33330313;    // addi x6,x6,0x333

    mem[41] = 32'h0062A023;    // sw x6,0(x5)


    // ---------------------------------------------------------
    // PT[127:96] = 0x44444444
    // ---------------------------------------------------------

    mem[42] = 32'h02C00293;    // addi x5,x0,0x2C

    mem[43] = 32'h44444337;    // lui  x6,0x44444
    mem[44] = 32'h44430313;    // addi x6,x6,0x444

    mem[45] = 32'h0062A023;    // sw x6,0(x5)


    // =========================================================
    // START
    // 0x00 = 1
    // =========================================================

    mem[46] = 32'h00000293;    // addi x5,x0,0
    mem[47] = 32'h00100313;    // addi x6,x0,1
    mem[48] = 32'h0062A023;    // sw x6,0(x5)


    // =========================================================
    // STATUS ADDRESS
    // x5 = 0x04
    // =========================================================

    mem[49] = 32'h00400293;    // addi x5,x0,0x04


    // =========================================================
    // POLL STATUS
    // =========================================================

    // lw x7,0(x5)
    mem[50] = 32'h0002A383;

    // andi x8,x7,4
    // ERROR bit
    mem[51] = 32'h0043F413;

    // if ERROR != 0 -> error_loop
    mem[52] = 32'h02041863;

    // andi x8,x7,2
    // DONE bit
    mem[53] = 32'h0023F413;

    // if DONE == 0 -> poll_status
    mem[54] = 32'hFE0408E3;


    // =========================================================
    // READ AES OUTPUT
    // =========================================================

    // AES_OUT_0 = 0x40
    mem[55] = 32'h04000293;
    mem[56] = 32'h0002A503;

    // AES_OUT_1 = 0x44
    mem[57] = 32'h04400293;
    mem[58] = 32'h0002A583;

    // AES_OUT_2 = 0x48
    mem[59] = 32'h04800293;
    mem[60] = 32'h0002A603;

    // AES_OUT_3 = 0x4C
    mem[61] = 32'h04C00293;
    mem[62] = 32'h0002A683;


    // =========================================================
    // SUCCESS LOOP
    // =========================================================

    mem[63] = 32'h0000006F;


    // =========================================================
    // ERROR LOOP
    // =========================================================

    mem[64] = 32'h0000006F;

end

assign Instruction = mem[pc[31:2]];

endmodule
